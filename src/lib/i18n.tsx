export type TranslationKey = keyof typeof translations.en;

export function getLocalizedToolMeta(
  tool: ToolMeta,
  t: (key: TranslationKey | string, params?: Record<string, string | number>) => string
) {
  const nameKey = `tool.meta.${tool.id}.name`;
  const descKey = `tool.meta.${tool.id}.desc`;
  const taglineKey = `tool.meta.${tool.id}.tagline`;
  const localizedName = t(nameKey);
  const localizedDesc = t(descKey);
  const localizedTagline = t(taglineKey);

  return {
    name: localizedName !== nameKey ? localizedName : tool.name,
    shortDescription: localizedDesc !== descKey ? localizedDesc : tool.shortDescription,
    tagline: localizedTagline !== taglineKey ? localizedTagline : tool.tagline,
  };
}

interface LanguageContextType {
  language: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: (key: TranslationKey | string, params?: Record<string, string | number>) => string;
  dir: 'ltr' | 'rtl';
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (key) => key,
  dir: 'ltr',
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<SupportedLanguage>(() => {
    if (typeof window === 'undefined') return 'en';
    const rootEl = typeof document !== 'undefined' ? document.getElementById('root') : null;
    if (rootEl && rootEl.hasAttribute('data-ssr-route')) {
      return 'en';
    }
    try {
      const saved = localStorage.getItem('pdfquick_lang') as SupportedLanguage;
      if (saved && (saved === 'en' || saved === 'es' || saved === 'fr' || saved === 'ar')) {
        return saved;
      }
      const navLang = navigator.language?.toLowerCase() || '';
      if (navLang.startsWith('es')) return 'es';
      if (navLang.startsWith('fr')) return 'fr';
      if (navLang.startsWith('ar')) return 'ar';
    } catch {
      // ignore
    }
    return 'en';
  });

  useEffect(() => {
    if (typeof window === 'undefined') return;
    try {
      const saved = localStorage.getItem('pdfquick_lang') as SupportedLanguage;
      if (saved && (saved === 'en' || saved === 'es' || saved === 'fr' || saved === 'ar')) {
        if (saved !== language) setLanguageState(saved);
        return;
      }
      const navLang = navigator.language?.toLowerCase() || '';
      const detected: SupportedLanguage = navLang.startsWith('es')
        ? 'es'
        : navLang.startsWith('fr')
          ? 'fr'
          : navLang.startsWith('ar')
            ? 'ar'
            : 'en';
      if (detected !== language) {
        setLanguageState(detected);
      }
    } catch {
      // ignore
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const currentOption = LANGUAGES.find((l) => l.code === language) || LANGUAGES[0];
  const dir = currentOption.dir || 'ltr';

  const setLanguage = (newLang: SupportedLanguage) => {
    setLanguageState(newLang);
    try {
      localStorage.setItem('pdfquick_lang', newLang);
      const opt = LANGUAGES.find((l) => l.code === newLang);
      if (typeof document !== 'undefined') {
        document.documentElement.lang = newLang;
        document.documentElement.dir = opt?.dir || 'ltr';
      }
      trackLanguageSwitch(newLang);
    } catch {
      // ignore
    }
  };

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = language;
      document.documentElement.dir = dir;
    }
  }, [language, dir]);

  const t = (key: TranslationKey | string, params?: Record<string, string | number>): string => {
    const langDict = (translations as any)[language] || translations.en;
    let text = langDict[key] || (translations.en as any)[key] || key;

    if (params) {
      Object.entries(params).forEach(([paramKey, val]) => {
        text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
      });
    }

    return text;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, dir }}>
      {children}
    </LanguageContext.Provider>
  );
};

export function useTranslation() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useTranslation must be used within a LanguageProvider');
  }
  return context;
}
